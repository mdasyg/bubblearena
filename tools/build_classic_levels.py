def validate_all():
    print(f"Validating {len(CLASSIC_LEVELS)} classic maps...")
    for lvl in CLASSIC_LEVELS:
        name = lvl["name"]
        m = lvl["map"]
        assert len(m) == 20, f"{name}: must have 20 rows, got {len(m)}"
        for r_idx, row in enumerate(m):
            assert len(row) == 30, f"{name} row {r_idx}: must have 30 cols, got {len(row)}: '{row}'"
            for c_idx, ch in enumerate(row):
                assert ch in "#=.1234F", f"{name} ({r_idx},{c_idx}): invalid char '{ch}'"
        
        # Check spawns
        spawns = {}
        for r in range(20):
            for c in range(30):
                ch = m[r][c]
                if ch in "1234F":
                    assert ch not in spawns, f"{name}: duplicate spawn {ch}"
                    spawns[ch] = (r, c)
                    
        for ch in "1234F":
            assert ch in spawns, f"{name}: missing spawn {ch}"
            r, c = spawns[ch]
            # Check headroom: row r-1 must be empty air '.'
            assert m[r-1][c] == ".", f"{name} spawn {ch}: headroom r-1 is '{m[r-1][c]}'"
            # Check support: within 2 rows below there must be a platform
            has_support = any(m[check_r][c] in "=#" for check_r in range(r+1, min(20, r+3)))
            assert has_support, f"{name} spawn {ch}: no platform support below at col {c}"
            
        # Reachability BFS
        def get_neighbors(r, c):
            for dr, dc in [(-1,0), (1,0), (0,-1), (0,1)]:
                nr, nc = r + dr, c + dc
                if 0 <= nr < 20 and 0 <= nc < 30:
                    if m[nr][nc] != "#":
                        yield (nr, nc)
                        
        start = spawns["1"]
        visited = set([start])
        q = deque([start])
        while q:
            curr = q.popleft()
            for n in get_neighbors(*curr):
                if n not in visited:
                    visited.add(n)
                    q.append(n)
                    
        for ch in "234F":
            target = spawns[ch]
            assert target in visited, f"{name}: spawn {ch} is trapped and unreachable from spawn 1!"
            
        print(f"  [OK] {name} passed all geometry and anti-trapping checks.")
    print("All classic maps verified successfully!")

def export_to_level_data(level_data_path="levels/level_data.py"):
    with open(level_data_path, "r", encoding="utf-8") as f:
        content = f.read()

    # Find the position of ALL_LEVELS = [
    marker = "ALL_LEVELS = ["
    if marker in content:
        base_content = content[:content.index(marker)].rstrip()
    else:
        base_content = content.rstrip()

    new_blocks = [base_content, ""]
    for idx, lvl in enumerate(CLASSIC_LEVELS, start=15):
        new_blocks.append(f"\nLEVEL_{idx} = {{")
        new_blocks.append(f'    "name": "{lvl["name"]}",')
        new_blocks.append(f'    "theme_id": {lvl["theme_id"]},')
        new_blocks.append('    "map": [')
        for row in lvl["map"]:
            new_blocks.append(f'        "{row}",')
        new_blocks.append("    ]")
        new_blocks.append("}")

    all_levels_items = [f"LEVEL_{k}" for k in range(1, 29)]
    new_blocks.append("\nALL_LEVELS = [")
    for i in range(0, 28, 5):
        chunk = all_levels_items[i:i+5]
        comma = "," if i + 5 < 28 else ""
        new_blocks.append("    " + ", ".join(chunk) + comma)
    new_blocks.append("]\n")

    with open(level_data_path, "w", encoding="utf-8") as f:
        f.write("\n".join(new_blocks))
    print(f"Successfully updated {level_data_path} with all 28 levels!")

if __name__ == "__main__":
    validate_all()
    export_to_level_data()
